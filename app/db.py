"""Data layer: SQLite locally, PostgreSQL in production (DATABASE_URL).

All application SQL uses the common subset of both dialects (?, named row access,
ON CONFLICT ... DO NOTHING/UPDATE, CHECK constraints, UNIQUE constraints). This module
translates the few genuinely dialect-specific pieces:
  - placeholders ? -> %s for Postgres
  - PRAGMA statements are SQLite-only
  - AUTOINCREMENT identity columns -> GENERATED BY DEFAULT AS IDENTITY
  - inserts into identity tables append RETURNING id so cursor.lastrowid works
  - datetime('now') defaults -> now()::timestamp(0)::text (TEXT timestamps everywhere)
Row access is by name in both modes (sqlite3.Row / RealDictRow).

Migrations run on every startup (app/migrations.py); the base schema is version 1.
"""
