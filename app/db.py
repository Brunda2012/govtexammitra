BASE_SCHEMA_VERSION = 1
SCHEMA = _SC.format(identity="INTEGER PRIMARY KEY AUTOINCREMENT", now="datetime('now')")
PG_SCHEMA = _SC.format(identity="INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                       now="now()::timestamp(0)::text")

def _translate_pg(sql: str, params):
    sql = sql.replace("?", "%s")
    if isinstance(params, dict):
        # named parameters (:name) — sqlite3 style; psycopg2 uses %(name)s
        for k in sorted(params, key=len, reverse=True):
            sql = sql.replace(":" + k, f"%({k})s")
    return sql

def _statements(script: str):
    for stmt in script.split(";"):
        if stmt.strip():
            yield stmt.strip()

class PGConnection:
    """Duck-types the sqlite3.Connection surface the app actually uses."""
    def __init__(self, url):
        import psycopg2
        import psycopg2.extras
        self._conn = psycopg2.connect(url)
        self._factory = psycopg2.extras.RealDictCursor

    def cursor(self):
        return PGCursor(self._conn.cursor(cursor_factory=self._factory), self._conn)

    def execute(self, sql, params=()):
        cur = self.cursor()
        cur.execute(sql, params)
        return cur

    def commit(self): self._conn.commit()
    def rollback(self): self._conn.rollback()
    def close(self): self._conn.close()

    def executescript(self, script):
        for stmt in _statements(script):
            self.execute(stmt)
        self.commit()

class PGCursor:
    def __init__(self, cur, conn):
        self._cur, self._conn = cur, conn
        self.lastrowid = None

    def execute(self, sql, params=()):
        sql = _translate_pg(sql, params)
        if isinstance(params, dict):
            params = {k: params[k] for k in params}
        returning = False
        stripped = sql.strip().upper()
        if stripped.startswith("INSERT INTO"):
            table = stripped[len("INSERT INTO"):].lstrip().split(None, 1)[0]
            if table in PG_IDENTITY_TABLES and "RETURNING" not in stripped:
                sql = sql.rstrip().rstrip(";") + " RETURNING id"
                returning = True
        self._cur.execute(sql, params)
        if returning:
            row = self._cur.fetchone()
            if row:
                self.lastrowid = row["id"]
        return self

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()

    def close(self):
        self._cur.close()

def get_conn(db_path=None):
    if db_path is None and PG_URL:
        return PGConnection(PG_URL)
    conn = sqlite3.connect(db_path or DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn

def init_db(db_path=None):
    from .migrations import run_migrations
    conn = get_conn(db_path)
    if isinstance(conn, PGConnection):
        conn.executescript(PG_SCHEMA)
    else:
        conn.executescript(SCHEMA)
    run_migrations(conn, sqlite_mode=not isinstance(conn, PGConnection))
    conn.commit()
    return conn

def row_to_dict(row):
    return {k: row[k] for k in row.keys()}

def rows_to_dicts(rows):
    return [row_to_dict(r) for r in rows]

def load_json_fields(d, fields):
    for f in fields:
        if d.get(f) and isinstance(d[f], str):
            try:
                d[f] = json.loads(d[f])
            except (ValueError, TypeError):
                pass
    return d
